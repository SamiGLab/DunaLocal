const menu = document.querySelector(".menu");
const navigation = document.querySelector(".navigation");
const buttons = [...document.querySelectorAll(".lang")];
function setLanguage(lang) {
  if (!copy[lang]) return;
  document.documentElement.lang = lang;
  document.title = lang === "hu" ? "Lokmira | Belső előnézet" : "Lokmira | Internal preview";
  const description = lang === "hu"
    ? "Lokmira belső előnézet: Google Cégprofil, helyi SEO, Google Ads, tartalom és mérhető megkeresések budapesti szolgáltatóknak."
    : "Internal preview: Lokmira local SEO, Google Ads, creative content and enquiry tracking for Budapest service businesses.";
  document.querySelector('meta[name="description"]').setAttribute("content", description);
  document.querySelector('meta[property="og:description"]').setAttribute("content", description);
  document.querySelector('meta[property="og:title"]').setAttribute("content", document.title);
  navigation.setAttribute("aria-label", lang === "hu" ? "Fő navigáció" : "Main navigation");
  document.querySelector(".logo").setAttribute("aria-label", lang === "hu" ? "Lokmira – lap teteje" : "Lokmira – back to top");
  for (const element of document.querySelectorAll("[data-i18n]")) {
    const key = element.getAttribute("data-i18n");
    if (Object.prototype.hasOwnProperty.call(copy[lang], key)) element.textContent = copy[lang][key];
  }
  const routes = {
    hu:{services:"/hu/szolgaltatasok/",approach:"/hu/modszer/",about:"/hu/rolunk/",contact:"/hu/kapcsolat/",seo:"/hu/helyi-seo/",ads:"/hu/google-ads/",creative:"/hu/tartalom-video/",measurement:"/hu/meres/"},
    en:{services:"/en/services/",approach:"/en/approach/",about:"/en/about/",contact:"/en/contact/",seo:"/en/local-seo/",ads:"/en/google-ads/",creative:"/en/content-video/",measurement:"/en/measurement/"}
  };
  for (const element of document.querySelectorAll("[data-route]")) {
    const route = element.dataset.route;
    if (Object.prototype.hasOwnProperty.call(routes[lang],route)) element.setAttribute("href",routes[lang][route]);
  }
  for (const button of buttons) {
    const selected = button.dataset.lang === lang;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", String(selected));
  }
  menu.setAttribute("aria-label", lang === "hu" ? "Menü megnyitása" : "Open navigation menu");
}
for (const button of buttons) button.addEventListener("click", () => setLanguage(button.dataset.lang));
menu.addEventListener("click", () => {
  const open = menu.getAttribute("aria-expanded") !== "true";
  menu.setAttribute("aria-expanded", String(open));
  navigation.classList.toggle("open", open);
});
navigation.addEventListener("click", (event) => {
  if (!event.target.closest("a")) return;
  menu.setAttribute("aria-expanded", "false");
  navigation.classList.remove("open");
});
setLanguage("hu");
